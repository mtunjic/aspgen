func patchRenoirAggregateField(r addRequest, m *Manifest, existing EntityMeta, newProps []Property) error {
	project := r.Project
	dir := filepath.Join(project, "src", m.Project+".DomainModel", existing.Context)
	aggPath := filepath.Join(dir, existing.Name+".cs")
	methodsPath := filepath.Join(dir, existing.Name+".Methods.cs")

	content, err := readPatchFile(aggPath)
	if err != nil {
		return err
	}
	newContent, changed := replaceArgList(content, existing.Properties, newProps, ctorParamPiece, leadingSpaceJoin)
	if !changed {
		return fmt.Errorf("aggregate %s: constructor parameter list not found", aggPath)
	}
	content = newContent

	last := existing.Properties[len(existing.Properties)-1]
	assignAnchor := domainAssignLine(last, true)
	var assignLines []string
	for _, p := range newProps {
		assignLines = append(assignLines, domainAssignLine(p, true))
	}
	newContent, changed = insertAfterAnchor(content, assignAnchor, "\n"+strings.Join(assignLines, "\n"), 1)
	if !changed {
		return fmt.Errorf("aggregate %s: constructor assignment %q not found", aggPath, assignAnchor)
	}
	content = newContent

	var declLines []string
	for _, p := range newProps {
		declLines = append(declLines, autoPropLine(p, "private set"))
	}
	newContent, changed = insertBeforeMarker(content, "    // aspgen:navigation", strings.Join(declLines, "\n"))
	if !changed {
		return missingMarkerErr(aggPath, "// aspgen:navigation")
	}
	if err := writePatchFile(aggPath, newContent, r.DryRun); err != nil {
		return err
	}

	content, err = readPatchFile(methodsPath)
	if err != nil {
		return err
	}
	newContent, changed = replaceArgList(content, existing.Properties, newProps, ctorParamPiece, leadingSpaceJoin)
	if !changed {
		return fmt.Errorf("aggregate methods %s: Update parameter list not found", methodsPath)
	}
	content = newContent
	newContent, changed = insertAfterAnchor(content, assignAnchor, "\n"+strings.Join(assignLines, "\n"), 1)
	if !changed {
		return fmt.Errorf("aggregate methods %s: Update assignment %q not found", methodsPath, assignAnchor)
	}
	content = newContent
	importAnchor := "        " + last.Name + " = other." + last.Name + ";"
	var importLines []string
	for _, p := range newProps {
		importLines = append(importLines, "        "+p.Name+" = other."+p.Name+";")
	}
	newContent, changed = insertAfterAnchor(content, importAnchor, "\n"+strings.Join(importLines, "\n"), 1)
	if !changed {
		return fmt.Errorf("aggregate methods %s: Import assignment %q not found", methodsPath, importAnchor)
	}
	if err := writePatchFile(methodsPath, newContent, r.DryRun); err != nil {
		return err
	}

	configPath := filepath.Join(project, "src", m.Project+".Persistence", existing.Name+"Configuration.cs")
	if err := patchRenoirConfiguration(configPath, existing.Name, newProps, r.DryRun); err != nil {
		return err
	}

	appDir := filepath.Join(project, "src", m.Project+".Application")
	crudPath := filepath.Join(appDir, existing.Name+"CrudService.cs")
	if _, err := os.Stat(crudPath); err == nil {
		if err := patchRenoirCrudService(crudPath, existing, newProps, r.DryRun); err != nil {
			return err
		}
		validatorPath := filepath.Join(appDir, existing.Name+"Validator.cs")
		if err := patchValidatorFile(validatorPath, "public "+existing.Name+"Validator()", newProps, true, r.DryRun); err != nil {
			return err
		}
	}

	razorPath := filepath.Join(project, "src", m.Project+".AppBlazor", "Components", "Pages", existing.Context, existing.Name+"Crud.razor")
	if _, err := os.Stat(razorPath); err == nil {
		if err := patchRenoirRazor(razorPath, existing, newProps, r.DryRun); err != nil {
			return err
		}
	}

	return nil
}
